const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = 'http://localhost:3002';
const api = 'http://localhost:3003/api/v1';
const output = path.resolve(process.cwd(), '../test-results/tour-detail');
fs.mkdirSync(output, { recursive: true });
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  context.setDefaultTimeout(30000);
  const page = await context.newPage();
  const errors = [];
  const checks = [];
  page.on('pageerror', error => errors.push(error.message));
  try {
    const tours = await (await context.request.get(`${api}/tours`)).json();
    const id = tours.data[0].id;
    await page.goto(`${base}/tours/${id}`);
    await page.getByRole('heading', { name: tours.data[0].title, exact: true }).waitFor();
    await page.getByRole('button', { name: 'Xem tất cả 3 ảnh' }).click();
    await page.getByRole('dialog').waitFor();
    await page.getByRole('button', { name: 'Đóng thư viện ảnh' }).click();
    await page.locator('details').nth(1).locator('summary').click();
    await page.getByText('Khám phá cảnh quan Tràng An bằng thuyền, đi qua những dãy núi đá vôi và hang động. Buổi chiều tận hưởng nhịp sống làng quê bằng xe đạp.').waitFor();
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.locator('img').evaluateAll(images => Promise.all(images.map(image => image.complete ? Promise.resolve() : new Promise(resolve => { image.onload = resolve; image.onerror = resolve; }))));
    await page.screenshot({ path: path.join(output, 'desktop.png'), fullPage: true });
    await page.screenshot({ path: path.join(output, 'desktop-hero.png') });
    assert.equal(await page.getByRole('link', { name: 'Bảo hiểm', exact: true }).count(), 0);
    assert.equal(/hotline/i.test(await page.getByRole('complementary', { name: 'Đặt tour' }).innerText()), false);
    checks.push('Reference layout, photo gallery dialog, detailed day accordion; no hotline or insurance module');
    await page.getByRole('tab', { name: 'Chính sách giá', exact: true }).click();
    assert.equal(await page.getByRole('heading', { name: 'Lịch trình chi tiết', exact: true }).count(), 0);
    await page.getByRole('tab', { name: 'Hướng dẫn', exact: true }).click();
    await page.getByRole('heading', { name: 'Giấy tờ tùy thân', exact: true }).waitFor();
    await page.screenshot({ path: path.join(output, 'guidance.png') });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: path.join(output, 'mobile.png'), fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    checks.push('Separate price/guidance sections and mobile without horizontal overflow');
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.goto(`${base}/login`);
    await page.locator('#user-credential').fill('traveler@chat.test');
    await page.locator('#user-password').fill('ChatSmoke2026!');
    await page.locator('form[data-purpose="login-form"] button[type="submit"]').click();
    await page.waitForURL(url => !url.pathname.includes('/login'));
    await page.goto(`${base}/tours/${id}`);
    await page.getByRole('button', { name: 'Tăng trẻ em', exact: true }).click();
    await page.getByRole('button', { name: 'Tăng em bé', exact: true }).click();
    assert.equal(await page.getByRole('button', { name: 'Thêm vào giỏ hàng', exact: true }).count(), 0);
    await page.getByRole('button', { name: 'Yêu cầu đặt tour', exact: true }).click();
    await page.waitForURL(/\/traveler\/bookings\/new/);
    await page.getByLabel('Số điện thoại', { exact: false }).fill('0901234567');
    const bookingResponse = page.waitForResponse(response => response.url() === `${api}/bookings` && response.request().method() === 'POST');
    await page.getByRole('button', { name: 'Xác nhận đặt chỗ', exact: true }).click();
    const booked = await (await bookingResponse).json();
    assert.equal(booked.data.totalAmount, 2250000);
    assert.equal(booked.data.guestPricing.childUnitPrice, 750000);
    assert.equal(booked.data.guestPricing.infantUnitPrice, 0);
    await page.waitForURL(/\/settings\/history\//);
    await page.getByRole('heading', { name: /Chi tiết thanh toán/ }).waitFor();
    await page.screenshot({ path: path.join(output, 'booking-breakdown.png'), fullPage: true });
    checks.push('Real UI: adults/children/infants pass directly to booking and persisted payment breakdown with correct total');
    const agencyContext = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
    agencyContext.setDefaultTimeout(30000);
    const agencyPage = await agencyContext.newPage();
    agencyPage.on('pageerror', error => errors.push(error.message));
    await agencyPage.goto(`${base}/agency/login`);
    await agencyPage.locator('input[type="email"]').fill('agency@chat.test');
    await agencyPage.locator('input[type="password"]').fill('ChatSmoke2026!');
    await agencyPage.locator('button[type="submit"]').click();
    await agencyPage.waitForURL(url => url.pathname === '/agency');
    await agencyPage.goto(`${base}/agency/tours/${id}/edit`);
    for (let step = 0; step < 3; step++) await agencyPage.getByRole('button', { name: 'Tiếp tục', exact: true }).click();
    await agencyPage.getByLabel('Áp dụng giá theo độ tuổi').waitFor();
    const documents = 'Giấy tờ tùy thân còn hiệu lực. Xác nhận giấy tờ trẻ em trước ngày khởi hành.';
    await agencyPage.getByLabel('Giấy tờ tùy thân', { exact: false }).fill(documents);
    await agencyPage.screenshot({ path: path.join(output, 'agency-policy-form.png'), fullPage: true });
    await agencyPage.getByRole('button', { name: 'Hoàn thiện', exact: true }).click();
    const savedResponse = agencyPage.waitForResponse(response => response.url() === `${api}/agency/tours/${id}` && response.request().method() === 'PATCH');
    await agencyPage.getByRole('button', { name: 'Tiếp tục', exact: true }).click();
    const saved = await savedResponse;
    assert.equal(saved.status(), 200);
    assert.equal((await saved.json()).data.requiredDocuments, documents);
    const publicTour = await (await context.request.get(`${api}/tours/${id}`)).json();
    assert.equal(publicTour.data.requiredDocuments, documents);
    checks.push('Agency editor loads age pricing, saves separate policy fields, and public detail returns saved data');
    assert.deepEqual(errors, []);
    const report = { passed: true, checks, errors };
    fs.writeFileSync(path.join(output, 'result.json'), JSON.stringify(report, null, 2));
    console.log(JSON.stringify({ ...report, output }, null, 2));
  } catch (error) {
    await page.screenshot({ path: path.join(output, 'failure.png'), fullPage: true }).catch(() => {});
    console.log((await page.locator('body').innerText().catch(() => '')).slice(-3000));
    throw error;
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
