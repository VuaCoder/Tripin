/* Run with CHAT_SMOKE_AI=1 on chat-browser-server.ts and frontend :3002. */
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = 'http://localhost:3002';
const api = 'http://localhost:3003/api/v1';
const output = path.resolve(process.cwd(), '../test-results/ai-chat-browser');
fs.mkdirSync(output, { recursive: true });

(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const errors = [];
  const context = await browser.newContext({ viewport: { width: 1365, height: 900 } });
  context.setDefaultTimeout(60000);
  try {
    const page = await context.newPage();
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(`${base}/login`);
    await page.locator('#user-credential').fill('traveler@chat.test');
    await page.locator('#user-password').fill('ChatSmoke2026!');
    const loginResponse = page.waitForResponse(r => r.url() === `${api}/auth/login` && r.request().method() === 'POST');
    await page.locator('form[data-purpose="login-form"] button[type="submit"]').click();
    const login = await (await loginResponse).json();
    assert.equal(login.success, true);
    const headers = { Authorization: `Bearer ${login.data.accessToken}` };
    await page.waitForURL(url => !url.pathname.includes('/login'));
    await page.goto(`${base}/conversations`);
    const aiRow = page.locator('a[href="/conversations/ai"]');
    await aiRow.getByText('AI: Hội An có phố cổ và nhiều món ngon.', { exact: true }).waitFor();
    await aiRow.getByLabel('1 tin chưa đọc').waitFor();
    await page.screenshot({ path: path.join(output, 'inbox-desktop.png'), fullPage: true });
    await aiRow.click();
    await page.getByRole('log').getByText('Hội An', { exact: true }).waitFor();
    await page.getByRole('log').getByText('Hôm nay', { exact: true }).waitFor();
    await aiRow.getByLabel('1 tin chưa đọc').waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: 'Lịch sử', exact: true }).click();
    const history = page.getByRole('region', { name: 'Lịch sử AI' });
    await history.getByText('Trang 1/2').waitFor();
    await page.screenshot({ path: path.join(output, 'history-desktop.png'), fullPage: true });
    await history.getByRole('button', { name: 'Sau', exact: true }).click();
    await history.getByText('Trang 2/2').waitFor();
    await history.getByRole('button', { name: /Lịch trình ngày 21/ }).click();
    await page.getByRole('log').getByText('Gợi ý cho ngày 21', { exact: true }).waitFor();
    const oldDate = new Date(); oldDate.setDate(oldDate.getDate() - 21);
    const dateLabel = `${String(oldDate.getDate()).padStart(2, '0')}/${String(oldDate.getMonth() + 1).padStart(2, '0')}/${oldDate.getFullYear()}`;
    await page.getByRole('log').getByText(dateLabel, { exact: true }).waitFor();
    const old = await (await context.request.get(`${api}/ai/conversations?page=2&limit=20`, { headers })).json();
    const oldId = old.data.find(c => c.title === 'Lịch trình ngày 21').id;
    await page.getByLabel('Nhập câu hỏi cho Trợ lý AI').fill('Tôi muốn tiếp tục lịch trình cũ');
    await page.getByRole('button', { name: 'Gửi câu hỏi', exact: true }).click();
    await page.getByRole('log').getByText('Bạn có thể ghé Hội An và dạo phố cổ vào buổi chiều.', { exact: true }).waitFor();
    const saved = await (await context.request.get(`${api}/ai/conversations/${oldId}`, { headers })).json();
    assert.equal(saved.data.messages.length, 4);
    await page.getByTitle('Bắt đầu cuộc trò chuyện mới').click();
    await page.getByText('Xin chào! Tôi có thể giúp gì cho chuyến đi của bạn?', { exact: true }).waitFor();
    const before = await (await context.request.get(`${api}/ai/conversations`, { headers })).json();
    assert.equal(before.meta.total, 22);
    await page.getByRole('button', { name: 'Lịch sử', exact: true }).click();
    await page.getByRole('region', { name: 'Lịch sử AI' }).getByRole('button', { name: /Lịch trình ngày 21/ }).click();
    await page.getByRole('log').getByText('Tôi muốn tiếp tục lịch trình cũ', { exact: true }).waitFor();
    await page.reload();
    await page.getByRole('log').getByText('Tôi muốn tiếp tục lịch trình cũ', { exact: true }).waitFor();
    // A second device sends while the first is on the inbox: count and preview update through Socket.IO.
    await page.goto(`${base}/conversations`);
    const incoming = await context.request.post(`${api}/ai/chat`, { headers, data: { conversationId: oldId, message: 'Tin từ thiết bị khác' } });
    assert.equal(incoming.status(), 200);
    await aiRow.getByLabel('1 tin chưa đọc').waitFor();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(output, 'inbox-mobile.png'), fullPage: true });
    await aiRow.click();
    await page.getByRole('log').getByText('Tin từ thiết bị khác', { exact: true }).waitFor();
    await page.getByRole('button', { name: 'Lịch sử', exact: true }).click();
    await page.screenshot({ path: path.join(output, 'history-mobile.png'), fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false, 'mobile horizontal overflow');
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ passed: true, checks: ['preview and unread', 'history pagination', 'old date groups', 'continue old chat', 'new chat preserves history', 'reload', 'socket update from another device', 'desktop and mobile'], output }));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
